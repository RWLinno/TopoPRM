#!/usr/bin/env bash
set -euo pipefail
###############################################################################
# exp_May17: Queue all missing experiments.
#
# Usage:
#   source .env   # load tokens first
#   bash scripts/run_exp_may17.sh [phase]
#
# Phases:
#   eval_gpqa    ? P0: run GPQA-D eval for topoprm_hier_9b_v3
#   train_nocont ? P0: re-train no_continuity ablation (mcl4096)
#   eval_nocont  ? P0: eval the re-trained no_continuity
#   train_scae   ? P1: train SCAE variant
#   eval_scae    ? P1: eval SCAE variant
#   all          ? run everything in sequence
###############################################################################

cd "$(dirname "$0")/.."
export PYTHONPATH="$(pwd):${PYTHONPATH:-}"

PHASE="${1:-all}"
GPUS="${CUDA_VISIBLE_DEVICES:-0,1,2,3,4}"
NUM_GPUS=$(echo "$GPUS" | tr ',' '\n' | wc -l)

MODEL_9B="/mnt/data/huggingface_downloads/models/qwen/Qwen3.5-9B"
HIER_ADAPTER="output/grpo_hierarchical_qwen35_9b_mcl4096/v2-20260407-162048/checkpoint-79"

log() { echo "[$(date +%H:%M:%S)] $*"; }

# ?????????????????????????????????????????????????????????????????????????????
# P0: Eval GPQA-D for topoprm_hier_9b_v3 (fills last missing cell)
# ?????????????????????????????????????????????????????????????????????????????
phase_eval_gpqa() {
    log "=== P0: Eval GPQA-D for topoprm_hier_9b_v3 ==="
    BENCHMARKS="gpqa_diamond" \
    NUM_SAMPLES=5 \
    KS="1 5" \
    SFT_STYLE=0 \
    USE_CHAT=1 \
    bash scripts/run_unified_eval.sh \
        "$MODEL_9B" \
        "$HIER_ADAPTER" \
        "topoprm_hier_9b_v3"
    log "GPQA-D eval done."
}

# ?????????????????????????????????????????????????????????????????????????????
# P0: Re-train no_continuity ablation (mcl4096, from raw base)
# ?????????????????????????????????????????????????????????????????????????????
phase_train_nocont() {
    log "=== P0: Train no_continuity (mcl4096) ==="
    if [ -d "output/grpo_no_continuity_qwen35_9b_mcl4096" ]; then
        log "WARNING: output dir exists, skipping. Delete it to re-run."
        return 0
    fi
    swift rlhf \
        --rlhf_type grpo \
        --config configs/grpo_no_continuity_qwen35_9b_mcl4096.yaml
    log "no_continuity training done."
}

# ?????????????????????????????????????????????????????????????????????????????
# P0: Eval no_continuity after re-training
# ?????????????????????????????????????????????????????????????????????????????
phase_eval_nocont() {
    log "=== P0: Eval no_continuity_9b_v4 ==="
    # Find latest checkpoint
    local CKPT
    CKPT=$(find output/grpo_no_continuity_qwen35_9b_mcl4096 -name "checkpoint-*" -type d | sort -V | tail -1)
    if [ -z "$CKPT" ]; then
        log "ERROR: no checkpoint found. Run train_nocont first."
        return 1
    fi
    log "Using checkpoint: $CKPT"
    BENCHMARKS="all" \
    NUM_SAMPLES=5 \
    KS="1 5" \
    SFT_STYLE=0 \
    USE_CHAT=1 \
    bash scripts/run_unified_eval.sh \
        "$MODEL_9B" \
        "$CKPT" \
        "no_continuity_9b_v4"
    log "no_continuity eval done."
}

# ?????????????????????????????????????????????????????????????????????????????
# P1: Train SCAE variant
# ?????????????????????????????????????????????????????????????????????????????
phase_train_scae() {
    log "=== P1: Train TopoPRM + SCAE (mcl4096) ==="
    if [ -d "output/grpo_topoprm_scae_qwen35_9b_mcl4096" ]; then
        log "WARNING: output dir exists, skipping."
        return 0
    fi
    swift rlhf \
        --rlhf_type grpo \
        --config configs/grpo_topoprm_scae_qwen35_9b_mcl4096.yaml
    log "SCAE training done."
}

# ?????????????????????????????????????????????????????????????????????????????
# P1: Eval SCAE variant
# ?????????????????????????????????????????????????????????????????????????????
phase_eval_scae() {
    log "=== P1: Eval topoprm_scae_9b ==="
    local CKPT
    CKPT=$(find output/grpo_topoprm_scae_qwen35_9b_mcl4096 -name "checkpoint-*" -type d | sort -V | tail -1)
    if [ -z "$CKPT" ]; then
        log "ERROR: no SCAE checkpoint found. Run train_scae first."
        return 1
    fi
    log "Using checkpoint: $CKPT"
    BENCHMARKS="all" \
    NUM_SAMPLES=5 \
    KS="1 5" \
    SFT_STYLE=0 \
    USE_CHAT=1 \
    bash scripts/run_unified_eval.sh \
        "$MODEL_9B" \
        "$CKPT" \
        "topoprm_scae_9b"
    log "SCAE eval done."
}

# ?????????????????????????????????????????????????????????????????????????????
# Dispatch
# ?????????????????????????????????????????????????????????????????????????????
case "$PHASE" in
    eval_gpqa)    phase_eval_gpqa ;;
    train_nocont) phase_train_nocont ;;
    eval_nocont)  phase_eval_nocont ;;
    train_scae)   phase_train_scae ;;
    eval_scae)    phase_eval_scae ;;
    all)
        phase_eval_gpqa
        phase_train_nocont
        phase_eval_nocont
        phase_train_scae
        phase_eval_scae
        ;;
    *)
        echo "Unknown phase: $PHASE"
        echo "Available: eval_gpqa train_nocont eval_nocont train_scae eval_scae all"
        exit 1
        ;;
esac

log "=== exp_May17 phase '$PHASE' complete ==="
